import { permissionProcedure, protectedProcedure, router } from "../../_core/trpc";
import {
  discrepancyCreateSchema,
  discrepancyListSchema,
  discrepancyResolveSchema,
  intakeIdSchema,
  intakeListSchema,
  packageCreateSchema,
  packageIdSchema,
  packageListSchema,
  packageMetadataSchema,
  receiveIntakeSchema,
  sortingBatchCreateSchema,
  sortingBatchIdSchema,
  sortingBatchListSchema,
  sortingBatchPackageSchema,
  verifyIntakeSchema,
  verifyPackageSchema,
  warehouseAssignmentCreateSchema,
  warehouseAssignmentListSchema,
  warehouseCreateSchema,
  warehouseDashboardSchema,
  warehouseEventListSchema,
  warehouseIdSchema,
  warehouseListSchema,
  warehouseUpdateSchema,
} from "../../../shared/validation/warehouseSchemas";
import {
  addPackageToBatch,
  assignUser,
  closeSortingBatch,
  createPackage,
  createSortingBatch,
  createWarehouse,
  dashboard,
  getIntake,
  getPackage,
  getSortingBatch,
  getWarehouse,
  listAssignments,
  listDiscrepancies,
  listEligibleHandoffs,
  listIntakes,
  listPackages,
  listSortablePackages,
  listSortingBatches,
  listWarehouseEvents,
  listWarehouses,
  markPackageDispatchReady,
  receiveIntake,
  recordDiscrepancy,
  removePackageFromBatch,
  resolveDiscrepancy,
  updatePackageMetadata,
  updateWarehouse,
  verifyIntake,
  verifyPackage,
} from "./service";

const view = permissionProcedure("warehouse.view");
const intake = permissionProcedure("warehouse.intake");
const sort = permissionProcedure("warehouse.sort");
const dispatch = permissionProcedure("warehouse.dispatch");
const manage = permissionProcedure("warehouse.manage");

export const warehouseRouter = router({
  list: view.input(warehouseListSchema).query(({ ctx, input }) => listWarehouses(ctx.user.id, input, ctx.user.role === "admin")),
  get: view.input(warehouseIdSchema).query(({ ctx, input }) => getWarehouse(ctx.user.id, input.warehouseId, ctx.user.role === "admin")),
  create: manage.input(warehouseCreateSchema).mutation(({ ctx, input }) => createWarehouse(ctx.user.id, input, ctx.user.role === "admin")),
  update: manage.input(warehouseUpdateSchema).mutation(({ ctx, input }) => {
    const { warehouseId, ...fields } = input;
    return updateWarehouse(ctx.user.id, warehouseId, fields, ctx.user.role === "admin");
  }),
  dashboard: view.input(warehouseDashboardSchema).query(({ ctx, input }) => dashboard(ctx.user.id, input.warehouseId, ctx.user.role === "admin")),
  assignments: manage.input(warehouseAssignmentListSchema).query(({ ctx, input }) => listAssignments(ctx.user.id, input.warehouseId, ctx.user.role === "admin")),
  assignUser: manage.input(warehouseAssignmentCreateSchema).mutation(({ ctx, input }) => assignUser(ctx.user.id, input, ctx.user.role === "admin")),
  eligibleHandoffs: view.input(warehouseIdSchema.partial()).query(({ ctx, input }) => listEligibleHandoffs(ctx.user.id, input.warehouseId, ctx.user.role === "admin")),
  receiveIntake: intake.input(receiveIntakeSchema).mutation(({ ctx, input }) => receiveIntake(ctx.user.id, input, ctx.user.role === "admin")),
  listIntakes: view.input(intakeListSchema).query(({ ctx, input }) => listIntakes(ctx.user.id, input, ctx.user.role === "admin")),
  getIntake: view.input(intakeIdSchema).query(({ ctx, input }) => getIntake(ctx.user.id, input.intakeId, ctx.user.role === "admin")),
  createPackage: intake.input(packageCreateSchema).mutation(({ ctx, input }) => createPackage(ctx.user.id, input, ctx.user.role === "admin")),
  listPackages: view.input(packageListSchema).query(({ ctx, input }) => listPackages(ctx.user.id, input, ctx.user.role === "admin")),
  listSortablePackages: sort.input(packageListSchema).query(({ ctx, input }) => listSortablePackages(ctx.user.id, input, ctx.user.role === "admin")),
  getPackage: view.input(packageIdSchema).query(({ ctx, input }) => getPackage(ctx.user.id, input.packageId, ctx.user.role === "admin")),
  updatePackageMetadata: intake.input(packageMetadataSchema).mutation(({ ctx, input }) => updatePackageMetadata(ctx.user.id, input, ctx.user.role === "admin")),
  verifyPackage: intake.input(verifyPackageSchema).mutation(({ ctx, input }) => verifyPackage(ctx.user.id, input.packageId, ctx.user.role === "admin")),
  verifyIntake: intake.input(verifyIntakeSchema).mutation(({ ctx, input }) => verifyIntake(ctx.user.id, input.intakeId, ctx.user.role === "admin")),
  reportDiscrepancy: intake.input(discrepancyCreateSchema).mutation(({ ctx, input }) => recordDiscrepancy(ctx.user.id, input, ctx.user.role === "admin")),
  resolveDiscrepancy: intake.input(discrepancyResolveSchema).mutation(({ ctx, input }) => resolveDiscrepancy(ctx.user.id, input, ctx.user.role === "admin")),
  listDiscrepancies: view.input(discrepancyListSchema).query(({ ctx, input }) => listDiscrepancies(ctx.user.id, input, ctx.user.role === "admin")),
  createSortingBatch: sort.input(sortingBatchCreateSchema).mutation(({ ctx, input }) => createSortingBatch(ctx.user.id, input, ctx.user.role === "admin")),
  listSortingBatches: view.input(sortingBatchListSchema).query(({ ctx, input }) => listSortingBatches(ctx.user.id, input, ctx.user.role === "admin")),
  getSortingBatch: view.input(sortingBatchIdSchema).query(({ ctx, input }) => getSortingBatch(ctx.user.id, input.batchId, ctx.user.role === "admin")),
  addPackageToBatch: sort.input(sortingBatchPackageSchema).mutation(({ ctx, input }) => addPackageToBatch(ctx.user.id, input, ctx.user.role === "admin")),
  removePackageFromBatch: sort.input(sortingBatchPackageSchema).mutation(({ ctx, input }) => removePackageFromBatch(ctx.user.id, input, ctx.user.role === "admin")),
  markPackageDispatchReady: dispatch.input(packageIdSchema).mutation(({ ctx, input }) => markPackageDispatchReady(ctx.user.id, input.packageId, ctx.user.role === "admin")),
  closeSortingBatch: dispatch.input(sortingBatchIdSchema).mutation(({ ctx, input }) => closeSortingBatch(ctx.user.id, input.batchId, ctx.user.role === "admin")),
  events: view.input(warehouseEventListSchema).query(({ ctx, input }) => listWarehouseEvents(ctx.user.id, input, ctx.user.role === "admin")),
});
